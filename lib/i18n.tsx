export function translateIngredientUnit(unit: string, language: Language) {
  return ingredientUnitLabels[language][unit] ?? unit
}

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>("en")
  const [ready, setReady] = useState(false)

  useEffect(() => {
    const storedLanguage = window.localStorage.getItem("language")
    if (storedLanguage && isLanguage(storedLanguage)) {
      setLanguage(storedLanguage)
    }
    setReady(true)
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
    if (ready) {
      window.localStorage.setItem("language", language)
    }
  }, [language, ready])

  const t = (key: TranslationKey) => messages[language][key]

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error("useLanguage must be used within a LanguageProvider")
  }
  return context
}
